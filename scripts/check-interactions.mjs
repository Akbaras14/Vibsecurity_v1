import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const scan = process.argv[2];
assert(scan, 'Pass a completed scan ID');
const base = 'http://127.0.0.1:3000';
const report = await fetch(`http://127.0.0.1:8000/api/scans/${scan}/export`).then(r => r.json());
const finding = report.findings.find(f => f.translation?.status === 'completed');
assert(finding);
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/scans/${scan}`);
  await page.locator('.findings-table tbody tr').first().waitFor();
  assert.equal(await page.locator('.scan-stages li').count(), 2);
  let requests = 0;
  await page.route('**/api/scans/*/findings?**', async route => {
    requests++;
    await new Promise(resolve => setTimeout(resolve, 700));
    await route.continue();
  });
  const query = finding.translation.title.split(/\s+/)[0];
  await page.getByRole('searchbox').pressSequentially(query, { delay: 20 });
  await page.waitForTimeout(400);
  assert.equal(requests, 1, 'Typing should issue one debounced search');
  assert(await page.locator('.findings-table tbody tr').count() > 0, 'Keep rows while filtering');
  assert.equal(await page.locator('.findings-section').getAttribute('aria-busy'), 'true');
  await page.waitForFunction(() => document.querySelector('.findings-section')?.getAttribute('aria-busy') === 'false');
  await page.locator(`a[href="/scans/${scan}/findings/${finding.id}"]`).first().waitFor();
  await page.getByRole('button', { name: 'Hapus filter Pencarian', exact: true }).click();
  assert.equal(await page.getByRole('searchbox').inputValue(), '');
  await page.waitForFunction(() => document.querySelector('.findings-section')?.getAttribute('aria-busy') === 'false');
  await page.goto(`${base}/scans/${scan}/findings/${finding.id}`);
  await page.getByRole('button', { name: 'Salin lokasi', exact: true }).click();
  await page.getByText('Tersalin ✓', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), `${finding.path}${finding.line ? `:${finding.line}` : ''}`);
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('denied'); }; });
  await page.getByRole('button', { name: 'Salin ringkasan bukti', exact: true }).click();
  await page.getByText('Gagal menyalin; coba lagi', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  const menu = page.getByRole('button', { name: 'Buka atau tutup navigasi' });
  await menu.click();
  assert.equal(await menu.getAttribute('aria-expanded'), 'true');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await menu.evaluate(node => node === document.activeElement), true);
  await page.keyboard.press('Escape');
  assert.equal(await menu.getAttribute('aria-expanded'), 'false');
  await menu.click();
  await page.getByRole('button', { name: 'Tutup navigasi', exact: true }).click({ position: { x: 350, y: 200 } });
  assert.equal(await menu.getAttribute('aria-expanded'), 'false');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.goto(`${base}/projects/${report.project.id}`);
  await page.locator('input[type=file]').waitFor();
  await page.locator('input[type=file]').setInputFiles({ name: 'wrong.txt', mimeType: 'text/plain', buffer: Buffer.from('test') });
  await page.getByRole('alert').filter({ hasText: 'Pilih satu ZIP' }).waitFor();
  const transfer = await page.evaluateHandle(() => {
    const data = new DataTransfer();
    data.items.add(new File(['test'], 'ux-example.zip', { type: 'application/zip' }));
    return data;
  });
  await page.locator('.upload-zone').dispatchEvent('drop', { dataTransfer: transfer });
  assert.equal(await page.getByRole('button', { name: 'Mulai pemindaian →', exact: true }).isEnabled(), true);
  await page.getByRole('button', { name: 'Hapus pilihan file', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Mulai pemindaian →', exact: true }).isEnabled(), false);
  assert.deepEqual(errors, []);
  console.log('Debounced Indonesian search, retained rows, chips, clipboard, mobile navigation and ZIP drop checks passed.');
} finally { await browser.close(); }
