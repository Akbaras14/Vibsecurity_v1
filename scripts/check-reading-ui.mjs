import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright';
const fixture = JSON.parse(await readFile('.cache/ui-check.json', 'utf8'));
const base = 'http://127.0.0.1:3000';
const api = 'http://127.0.0.1:8000/api';
const findings = (await fetch(`${api}/scans/${fixture.scan}/findings`).then(r => r.json())).data;
const finding = findings.find(item => item.method === 'sast');
assert(finding, 'The controlled scan must have a real SAST finding.');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [];
let metadataProject;
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/projects/new`);
  await page.getByLabel('Nama proyek').fill('[UJI UI] Metadata kelompok sampel');
  await page.getByText('Data penelitian dan asal proyek (opsional)', { exact: true }).click();
  await page.getByLabel('Kelompok sampel').selectOption('chatbot');
  await page.getByRole('button', { name: 'Buat proyek', exact: true }).click();
  await page.waitForURL(/\/projects\/[a-f0-9]{32}$/);
  metadataProject = new URL(page.url()).pathname.split('/').at(-1);
  const metadata = (await fetch(`${api}/projects/${metadataProject}`).then(r => r.json())).data;
  assert.equal(metadata.sample_group, 'chatbot');
  await page.getByRole('button', { name: 'Hapus proyek', exact: true }).click();
  await page.getByRole('button', { name: 'Ya, hapus proyek', exact: true }).click();
  await page.waitForURL(`${base}/projects`);
  metadataProject = null;
  await page.goto(`${base}/scans/${fixture.scan}`);
  const list = page.getByRole('heading', { name: 'Daftar temuan', exact: true });
  await list.waitFor();
  await page.locator('summary').filter({ hasText: /^Distribusi hasil$/ }).click();
  const distribution = page.getByRole('heading', { name: 'Distribusi hasil', exact: true });
  assert((await list.boundingBox()).y < (await distribution.boundingBox()).y);
  await page.screenshot({ path: '.cache/screenshots/scan-after.png', fullPage: true });
  await page.goto(`${base}/scans/${fixture.scan}/findings/${finding.id}`);
  await page.getByRole('heading', { name: 'Bukti dan lokasi kerentanan', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Hasil analisis otomatis', exact: true }).waitFor();
  const stored = (await fetch(`${api}/scans/${fixture.scan}/findings/${finding.id}`).then(r => r.json())).data;
  assert.equal(stored.automatic.engine, 'AUTO1');
  assert.notEqual(stored.review_status, 'unreviewed');
  assert.equal(await page.getByRole('button', { name: 'Simpan keputusan baru', exact: true }).count(), 0);
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: '.cache/screenshots/finding-after.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/scans/${fixture.scan}`);
  await page.getByRole('heading', { name: 'Daftar temuan', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '.cache/screenshots/scan-after-mobile.png', fullPage: true });
  await page.goto(`${base}/scans/${fixture.scan}/findings/${finding.id}`);
  await page.getByRole('heading', { name: 'Bukti dan lokasi kerentanan', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '.cache/screenshots/finding-after-mobile.png', fullPage: true });
  await page.goto(`${base}/scans/${fixture.scan}/report`);
  await page.getByRole('heading', { name: 'Identitas analisis', exact: true }).waitFor();
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.sidebar').isVisible(), false);
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.emulateMedia({ media: 'screen' });
  await page.goto(`${base}/dashboard`);
  await page.getByText('Rekap penelitian', { exact: true }).click();
  await page.getByRole('heading', { name: 'Rancangan 12 sampel penelitian', exact: true }).waitFor();
  await page.screenshot({ path: '.cache/screenshots/dashboard-after.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Reading UI passed: findings first, automatic assessment, retained evidence, mobile layout, report print, thesis dashboard.');
} finally {
  if (metadataProject) await fetch(`${api}/projects/${metadataProject}`, { method: 'DELETE' });
  await browser.close();
}

